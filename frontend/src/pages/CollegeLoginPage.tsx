import React, { useState } from "react";
import { Link, useLocation, useNavigate } from "react-router-dom";
import { useAuth } from "../auth/AuthContext";
import { Button } from "../components/ux4g/Button";
import { Input } from "../components/ux4g/Input";
import { FormField } from "../components/ux4g/FormField";
import { Card, CardBody } from "../components/ux4g/Card";
import { Badge } from "../components/ux4g/Badge";
import { Alert } from "../components/ux4g/Alert";
import { Icon } from "../components/ux4g/Icon";
import { useDocumentTitle } from "../hooks/useDocumentTitle";
import { PRODUCT_NAME } from "../brand";

export function CollegeLoginPage() {
  useDocumentTitle("College Portal Login");
  const { login, verifyMfa, cancelMfa, pendingMfa } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();

  const [email, setEmail] = useState("");
  const [password, setPassword] = useState("");
  const [mfaCode, setMfaCode] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const fromLocation = (
    location.state as { from?: { pathname: string; search?: string; hash?: string } }
  )?.from;
  const returnUrl = fromLocation
    ? `${fromLocation.pathname}${fromLocation.search || ""}${fromLocation.hash || ""}`
    : null;

  const getTargetDashboard = (userRole?: string) => {
    if (returnUrl) return returnUrl;
    if (userRole === "aicte_admin" || userRole === "aicte_officer") return "/aicte/overview";
    if (userRole === "verifier") return "/verifier/search";
    return "/college/dashboard";
  };

  const handleCredentialsSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setIsLoading(true);

    try {
      const res = await login({ email, password });
      if (!res.mfaRequired) {
        navigate(getTargetDashboard(res.user?.role), { replace: true });
      }
    } catch (err) {
      setError(
        err instanceof Error ? err.message : "Sign-in failed. Check your email and password."
      );
    } finally {
      setIsLoading(false);
    }
  };

  const handleMfaSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);
    setIsLoading(true);

    try {
      await verifyMfa(mfaCode);
      navigate(getTargetDashboard(), { replace: true });
    } catch (err) {
      setError(
        err instanceof Error
          ? err.message
          : "Invalid code. Enter the 6-digit code sent to your device."
      );
    } finally {
      setIsLoading(false);
    }
  };

  const quickFill = (demoEmail: string) => {
    setEmail(demoEmail);
    setPassword("Demo@12345");
    setError(null);
  };

  return (
    <div className="max-w-md mx-auto py-6 space-y-6">
      {/* Header */}
      <div className="text-center space-y-2">
        <div className="w-12 h-12 rounded-xl border ux4g-border-neutral-subtle ux4g-bg-neutral-soft mx-auto flex items-center justify-center shadow-sm">
          <Icon name="domain" size="lg" color="primary" aria-hidden="true" />
        </div>
        <h1 className="text-2xl font-bold ux4g-text-neutral-primary tracking-tight">College Portal Login</h1>
        <p className="text-xs ux4g-text-neutral-secondary">
          Sign in to manage student records, declare intake seats, and resolve validation flags.
        </p>
      </div>

      {error && (
        <Alert variant="error" title="Sign-in Error">
          {error}
        </Alert>
      )}

      <Card variant="outline" className="p-6">
        <CardBody className="p-0">
          {pendingMfa ? (
            /* MFA Step */
            <form onSubmit={handleMfaSubmit} className="space-y-4" data-testid="college-mfa-form">
              <div className="p-3 border ux4g-border-primary ux4g-bg-primary-soft rounded-lg flex items-center gap-3">
                <Icon name="verified_user" size="md" color="primary" className="shrink-0" aria-hidden="true" />
                <div className="text-xs ux4g-text-neutral-primary">
                  <p className="font-semibold">Two-Factor Authentication Required</p>
                  <p className="ux4g-text-neutral-secondary">Enter the 6-digit TOTP code generated by your authenticator app.</p>
                </div>
              </div>

              <FormField
                id="college-mfa-input"
                label="Authenticator Code"
                hint="6-digit time-based one-time password"
                required
              >
                <Input
                  id="college-mfa-input"
                  type="text"
                  inputMode="numeric"
                  pattern="[0-9]*"
                  maxLength={8}
                  placeholder="123456"
                  required
                  value={mfaCode}
                  onChange={(e) => setMfaCode(e.target.value)}
                  autoFocus
                />
              </FormField>

              <div className="flex items-center gap-3 pt-2">
                <Button
                  type="button"
                  variant="outline"
                  className="w-1/3"
                  onClick={cancelMfa}
                  disabled={isLoading}
                >
                  Cancel
                </Button>
                <Button
                  type="submit"
                  variant="primary"
                  className="w-2/3"
                  isLoading={isLoading}
                  loadingText="Verifying..."
                >
                  Verify and sign in
                </Button>
              </div>
            </form>
          ) : (
            /* Credentials Form */
            <form onSubmit={handleCredentialsSubmit} className="space-y-4">
              <FormField id="college-email-input" label="Official Institutional Email" required>
                <Input
                  id="college-email-input"
                  type="email"
                  placeholder="admin@college.edu.in"
                  required
                  value={email}
                  onChange={(e) => setEmail(e.target.value)}
                  autoComplete="email"
                />
              </FormField>

              <FormField id="college-password-input" label="Password" required>
                <Input
                  id="college-password-input"
                  type="password"
                  placeholder="••••••••••••"
                  required
                  value={password}
                  onChange={(e) => setPassword(e.target.value)}
                  autoComplete="current-password"
                />
              </FormField>

              <div className="flex items-center justify-between text-xs pt-1">
                <span className="ux4g-text-neutral-tertiary">MFA prompt required for admin accounts</span>
                <a href="#reset" className="ux4g-text-brand-primary hover:underline font-medium">
                  Forgot password?
                </a>
              </div>

              <Button
                type="submit"
                variant="primary"
                fullWidth
                isLoading={isLoading}
                loadingText="Signing in..."
                leftIcon={<Icon name="key" size="xs" color="inherit" aria-hidden="true" />}
              >
                Sign in as college
              </Button>
            </form>
          )}
        </CardBody>
      </Card>

      {/* Demo Accounts Helper */}
      {!pendingMfa && (
        <div className="border ux4g-border-neutral-subtle ux4g-bg-neutral-soft rounded-xl p-4 space-y-3 text-xs">
          <div className="flex items-center justify-between">
            <span className="font-semibold ux4g-text-neutral-primary">SIH 2026 Evaluation Demo Accounts:</span>
            <span className="font-mono ux4g-text-neutral-secondary">Password: Demo@12345</span>
          </div>

          <div className="space-y-1.5">
            <button
              type="button"
              aria-label="Fill demo credentials for Pune Institute (clean stage)"
              onClick={() => quickFill("admin@piaet-pune.edu.in")}
              className="w-full text-left p-2 rounded-lg border ux4g-border-neutral-subtle ux4g-bg-neutral-elevated hover:border-current transition flex justify-between items-center"
            >
              <div>
                <p className="font-medium ux4g-text-neutral-primary">Pune Inst. of Adv. Engg &amp; Tech</p>
                <p className="text-[11px] ux4g-text-neutral-secondary font-mono">admin@piaet-pune.edu.in</p>
              </div>
              <Badge variant="success">Clean Stage</Badge>
            </button>

            <button
              type="button"
              aria-label="Fill demo credentials for Mumbai Institute (exceptions stage)"
              onClick={() => quickFill("admin@mmit-mumbai.ac.in")}
              className="w-full text-left p-2 rounded-lg border ux4g-border-neutral-subtle ux4g-bg-neutral-elevated hover:border-current transition flex justify-between items-center"
            >
              <div>
                <p className="font-medium ux4g-text-neutral-primary">Mumbai Metropolitan Inst. of Tech</p>
                <p className="text-[11px] ux4g-text-neutral-secondary font-mono">admin@mmit-mumbai.ac.in</p>
              </div>
              <Badge variant="warning">Exceptions</Badge>
            </button>

            <button
              type="button"
              aria-label="Fill demo credentials for Nagpur College (draft stage)"
              onClick={() => quickFill("admin@ngec-nagpur.gov.in")}
              className="w-full text-left p-2 rounded-lg border ux4g-border-neutral-subtle ux4g-bg-neutral-elevated hover:border-current transition flex justify-between items-center"
            >
              <div>
                <p className="font-medium ux4g-text-neutral-primary">Nagpur Govt Engineering College</p>
                <p className="text-[11px] ux4g-text-neutral-secondary font-mono">admin@ngec-nagpur.gov.in</p>
              </div>
              <Badge variant="neutral">Draft Stage</Badge>
            </button>

            <button
              type="button"
              aria-label="Fill demo credentials for TCS Verifier"
              onClick={() => quickFill("verifier@tcs-verifications.com")}
              className="w-full text-left p-2 rounded-lg border ux4g-border-neutral-subtle ux4g-bg-neutral-elevated hover:border-current transition flex justify-between items-center"
            >
              <div>
                <p className="font-medium ux4g-text-neutral-primary">Tata Consultancy Services (Verifier)</p>
                <p className="text-[11px] ux4g-text-neutral-secondary font-mono">verifier@tcs-verifications.com</p>
              </div>
              <Badge variant="primary">Verifier Portal</Badge>
            </button>
          </div>
        </div>
      )}

      <div className="text-center text-xs ux4g-text-neutral-secondary space-y-1">
        <p>Has your institution not been activated on {PRODUCT_NAME} yet?</p>
        <Link to="/activate" className="font-semibold ux4g-text-brand-primary hover:underline">
          Claim AICTE Institution ID &amp; Activate
        </Link>
      </div>
    </div>
  );
}
